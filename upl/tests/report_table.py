"""Turn a pytest JUnit file into the test-results table for the report (guide Template A7).
usage: python -m pytest tests --junitxml=docs/test-results.xml && python tests/report_table.py docs/test-results.xml docs/7-test-results.md"""
import sys, xml.etree.ElementTree as ET
CAT = {"chain": ("Chain and trust", "R4, R5"), "issuance": ("Wrong issuance", "R4, R6"),
       "expiry": ("Expiry and revocation", "R6, R7"), "revocation": ("Expiry and revocation", "R6, R7"),
       "downgrade": ("Downgrade", "R5"), "signing": ("Report signing", "R8"), "ai": ("AI-driven threat", "R13"),
       "upload": ("Upload service", "R6"), "keys": ("Key protection", "R9"), "auth": ("Authentication", "R5, R9")}
src, dst = sys.argv[1], sys.argv[2]
root = ET.parse(src).getroot()
rows, counts = [], {}
for i, tc in enumerate(root.iter("testcase"), 1):
    name = tc.get("name"); prefix = name.split("_", 2)[1] if name.count("_") >= 2 else "other"
    cat, req = CAT.get(prefix, ("Other", "-"))
    if name.startswith("test_web_"):  # web application checks: category from the keyword in the name
        WEB = [("sqli", "SQL injection"), ("xss", "XSS"), ("csrf", "CSRF"), ("idor", "IDOR"), ("unauthorized", "Unauthorized transaction"),
               ("duplicate", "Duplicate transaction"), ("login_rate", "Brute-force protection"), ("session", "Session and cookie"),
               ("upload", "Malicious file upload"), ("headers", "Security headers"), ("https", "Security headers"), ("role", "Role authorization"),
               ("transfer", "Transaction validation")]
        cat = next((c for k, c in WEB if k in name), "Web application")
        req = "web"
    failed = any(c.tag in ("failure", "error") for c in tc)
    result = "FAIL" if failed else "PASS"
    counts[cat] = counts.get(cat, 0) + 1
    rows.append(f"| TC-{i:02d} | {req} | {cat} | `{name}` | {result} |")
total = len(rows); passed = sum(1 for r in rows if r.endswith("PASS |"))
out = ["# Test results (generated)", "",
       f"Run: {total} tests, {passed} passed, {total - passed} failed. Generated by `tests/report_table.py` from the JUnit file.",
       "", "Minimum per category (guide Section 7): chain 3, wrong issuance 2, expiry and revocation 3, downgrade 2, report signing 2, AI-driven threat 1. Total required: 13.", "",
       "| ID | Req. | Category | Test | Result |", "|---|---|---|---|---|", *rows, "", "## Count per category", ""]
out += [f"- {k}: {v}" for k, v in sorted(counts.items())]
open(dst, "w").write("\n".join(out) + "\n")
print(f"wrote {dst}: {passed}/{total} passed")
